CREATE TABLE proyectos (
    proyecto_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    cliente_id            NUMBER        NOT NULL,
    nombre                VARCHAR2(200) NOT NULL,
    descripcion           VARCHAR2(4000),
    fecha_inicio_estimada DATE,
    created_by            VARCHAR2(255) NOT NULL,
    created_at            TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by            VARCHAR2(255),
    updated_at            TIMESTAMP(6),
    CONSTRAINT uq_proyectos_cliente_nombre UNIQUE (cliente_id, nombre),
    CONSTRAINT fk_proyectos_cliente        FOREIGN KEY (cliente_id) REFERENCES clientes (cliente_id)
);

CREATE INDEX ix_proyectos_cliente ON proyectos (cliente_id);

CREATE TABLE versiones_estimacion (
    version_estimacion_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    proyecto_id           NUMBER     NOT NULL,
    numero_version        NUMBER(4,0) NOT NULL,
    created_by            VARCHAR2(255) NOT NULL,
    created_at            TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by            VARCHAR2(255),
    updated_at            TIMESTAMP(6),
    CONSTRAINT ck_versiones_est_numero  CHECK (numero_version > 0),
    CONSTRAINT uq_versiones_est_numero  UNIQUE (proyecto_id, numero_version),
    CONSTRAINT fk_versiones_est_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos (proyecto_id)
);

CREATE INDEX ix_versiones_est_proyecto ON versiones_estimacion (proyecto_id);


