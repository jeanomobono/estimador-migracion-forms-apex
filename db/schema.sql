-- -----------------------------------------------------------------------------
-- TABLAS BASE (sin dependencias externas)
-- -----------------------------------------------------------------------------

CREATE TABLE paises (
    pais_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR2(100)  NOT NULL,
    codigo_iso CHAR(2),
    activo     CHAR(1)        DEFAULT 'S' NOT NULL,
    CONSTRAINT ck_paises_activo UNIQUE (nombre),
    CONSTRAINT uq_paises_nombre CHECK (activo IN ('S','N'))
);

CREATE TABLE parametros_complejidad (
    parametro_complejidad_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    tipo_elemento            VARCHAR2(20)  NOT NULL,
    nivel_complejidad        VARCHAR2(20),
    horas                    NUMBER(6,2)   NOT NULL,
    updated_by               VARCHAR2(255),
    updated_at               TIMESTAMP(6),
    CONSTRAINT ck_param_complejidad_tipo  CHECK (tipo_elemento IN ('FORMULARIO','REPORTE','PLSQL','MENU')),
    CONSTRAINT ck_param_complejidad_nivel CHECK (nivel_complejidad IN ('SIMPLE','SEMI_COMPLEJO','COMPLEJO','MUY_COMPLEJO','MUY_COMPLEJO_PLUS') OR nivel_complejidad IS NULL),
    CONSTRAINT ck_param_complejidad_menu  CHECK ((tipo_elemento = 'MENU' AND nivel_complejidad IS NULL) OR (tipo_elemento <> 'MENU' AND nivel_complejidad IS NOT NULL)),
    CONSTRAINT ck_param_complejidad_horas CHECK (horas > 0),
    CONSTRAINT uq_param_complejidad       UNIQUE (tipo_elemento, nivel_complejidad)
);

CREATE TABLE parametros_etapa_case (
    parametro_etapa_case_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    etapa                   VARCHAR2(20)  NOT NULL,
    orden                   NUMBER(2,0)   NOT NULL,
    peso_porcentaje         NUMBER(5,2)   NOT NULL,
    recursos_paralelos      NUMBER(4,2)   NOT NULL,
    updated_by              VARCHAR2(255),
    updated_at              TIMESTAMP(6),
    CONSTRAINT ck_param_etapa_case_etapa CHECK (etapa IN ('ESTRATEGIA','ANALISIS','DISENO','CONSTRUCCION','TRANSICION')),
    CONSTRAINT ck_param_etapa_case_peso  CHECK (peso_porcentaje >= 0),
    CONSTRAINT ck_param_etapa_case_recur CHECK (recursos_paralelos > 0),
    CONSTRAINT uq_param_etapa_case_etapa UNIQUE (etapa),
    CONSTRAINT uq_param_etapa_case_orden UNIQUE (orden)
);

CREATE TABLE parametros_tiempo_adicional (
    parametro_tiempo_adicional_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    concepto                      VARCHAR2(40)  NOT NULL,
    base_calculo                  VARCHAR2(30)  NOT NULL,
    porcentaje                    NUMBER(5,2)   NOT NULL,
    orden                         NUMBER(2,0)   NOT NULL,
    updated_by                    VARCHAR2(255),
    updated_at                    TIMESTAMP(6),
    CONSTRAINT ck_param_tiempo_adic_conc CHECK (concepto IN ('PRUEBA_FUNCIONAL','ADMINISTRACION','CONTROL_CALIDAD','DBA','DOCUMENTACION')),
    CONSTRAINT ck_param_tiempo_adic_base CHECK (base_calculo IN ('PROGRAMACION','SUBTOTAL_CONSTRUCCION')),
    CONSTRAINT ck_param_tiempo_adic_pct  CHECK (porcentaje >= 0),
    CONSTRAINT uq_param_tiempo_adic_concepto UNIQUE (concepto),
    CONSTRAINT uq_param_tiempo_adic_orden    UNIQUE (orden)
);


-- -----------------------------------------------------------------------------
-- CLIENTES y CONTACTOS
-- -----------------------------------------------------------------------------

CREATE TABLE clientes (
    cliente_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR2(200) NOT NULL,
    direccion  VARCHAR2(400),
    ciudad     VARCHAR2(200),
    pais_id    NUMBER,
    created_by VARCHAR2(255),
    created_at TIMESTAMP(6)  DEFAULT SYSTIMESTAMP,
    updated_by VARCHAR2(255),
    updated_at TIMESTAMP(6),
    CONSTRAINT uq_clientes_nombre UNIQUE (nombre),
    CONSTRAINT fk_clientes_pais   FOREIGN KEY (pais_id) REFERENCES paises (pais_id)
);

CREATE TABLE contactos_cliente (
    contacto_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    cliente_id  NUMBER        NOT NULL,
    descripcion VARCHAR2(200) NOT NULL,
    telefono    VARCHAR2(50),
    email       VARCHAR2(200),
    orden       NUMBER        DEFAULT 10 NOT NULL,
    CONSTRAINT fk_contactos_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (cliente_id)
);

CREATE INDEX idx_contactos_cliente ON contactos_cliente (cliente_id);


-- -----------------------------------------------------------------------------
-- PROYECTOS y VERSIONES DE ESTIMACIÓN
